Future<Iterable<CommandOptionChoiceBuilder<String>>> roleplayChoices(
    AutocompleteContext context) async {
  final locale = context.interaction.locale;
  final search = context.currentValue.toLowerCase();
  return _actions.entries
      .map((entry) => (entry.key, entry.value.label(locale)))
      .where((entry) =>
          entry.$1.contains(search) || entry.$2.toLowerCase().contains(search))
      .take(25)
      .map((entry) => CommandOptionChoiceBuilder(name: entry.$2, value: entry.$1));
}

